import { readFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "..");

export async function loadMcpPackage(root = repositoryRoot) {
  const server = JSON.parse(
    await readFile(path.join(root, "packages", "mcp", "server.json"), "utf8")
  );
  const npmPackage = server.packages?.find((entry) => entry.registryType === "npm");
  if (!npmPackage?.identifier || !npmPackage?.version) {
    throw new Error("packages/mcp/server.json does not define a versioned npm package.");
  }
  return { identifier: npmPackage.identifier, version: npmPackage.version };
}

export function buildMcpConfig(packageMetadata) {
  return {
    command: "npx",
    args: ["-y", `${packageMetadata.identifier}@${packageMetadata.version}`]
  };
}

export function buildInstallLinks(packageMetadata) {
  const name = "martin-loop";
  const config = buildMcpConfig(packageMetadata);
  const cursorConfig = Buffer.from(JSON.stringify(config), "utf8").toString("base64");
  const cursorParams = new URLSearchParams({ name, config: cursorConfig });
  const vscodePayload = encodeURIComponent(JSON.stringify({ name, ...config }));

  return {
    cursor: `cursor://anysphere.cursor-deeplink/mcp/install?${cursorParams.toString()}`,
    vscode: `vscode:mcp/install?${vscodePayload}`,
    vscodeInsiders: `vscode-insiders:mcp/install?${vscodePayload}`
  };
}

export function renderMarkdown(packageMetadata, links) {
  return [
    "<!-- Generated by scripts/generate-install-links.mjs. -->",
    `<!-- MCP package: ${packageMetadata.identifier}@${packageMetadata.version} -->`,
    "",
    `[![Install in VS Code](https://img.shields.io/badge/VS_Code-Install_MartinLoop-007ACC?logo=visualstudiocode&logoColor=white)](${links.vscode})`,
    `[![Add to Cursor](https://img.shields.io/badge/Cursor-Add_MartinLoop-111111)](${links.cursor})`,
    ""
  ].join("\n");
}

async function main() {
  const packageMetadata = await loadMcpPackage();
  const links = buildInstallLinks(packageMetadata);
  if (process.argv.includes("--markdown")) {
    process.stdout.write(renderMarkdown(packageMetadata, links));
    return;
  }
  process.stdout.write(`${JSON.stringify({ package: packageMetadata, links }, null, 2)}\n`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await main();
}
