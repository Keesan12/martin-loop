import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/u;

export async function readMcpPackageVersion(packageDir) {
  const manifest = JSON.parse(await readFile(path.join(packageDir, "package.json"), "utf8"));
  const version = manifest.version;
  if (typeof version !== "string" || !SEMVER.test(version)) {
    throw new Error(`invalid or missing version in package.json: ${JSON.stringify(version)}`);
  }
  return version;
}

export function renderMcpRuntimeVersion(version) {
  return [
    "// Auto-generated by build — do not edit by hand.",
    "// Source of truth: packages/mcp/package.json#version",
    `export const MARTIN_MCP_PACKAGE_VERSION = "${version}";`,
    "",
  ].join("\n");
}

export async function writeMcpRuntimeVersion(packageDir) {
  const version = await readMcpPackageVersion(packageDir);
  await writeFile(
    path.join(packageDir, "src", "package-version.ts"),
    renderMcpRuntimeVersion(version),
    "utf8",
  );
  return version;
}
